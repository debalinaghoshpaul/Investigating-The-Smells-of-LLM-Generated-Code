import java.util.TreeSet;

public class CreateTreeSet {

    public static void main(String[] args) {
        // Create a tree set
        TreeSet<String> colors = new TreeSet<>();

        // Add some colors to the tree set
        colors.add("Red");
        colors.add("Green");
        colors.add("Blue");
        colors.add("Orange");
        colors.add("Yellow");

        // Print out the tree set
        System.out.println(colors);
    }
}
