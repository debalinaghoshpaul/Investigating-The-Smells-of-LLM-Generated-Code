// Java program to display the first 10 natural numbers

public class NaturalNumbers {

    public static void main(String[] args) {
        // Initialize the first natural number
        int number = 1;

        // Iterate until the 10th natural number is reached
        while (number <= 10) {
            // Display the current natural number
            System.out.println(number);

            // Increment the natural number by 1
            number++;
        }
    }
}
