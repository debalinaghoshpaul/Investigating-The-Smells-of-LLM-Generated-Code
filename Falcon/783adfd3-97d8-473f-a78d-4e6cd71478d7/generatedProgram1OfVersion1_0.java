import java.util.Scanner;

public class CheckJava {
    public static void main(String[] args) {
        Scanner scanner = new Scanner(System.in);
        System.out.println("Java Version: " + scanner.nextLine());
        System.out.println("Java Runtime Version: " + scanner.nextLine());
        System.out.println("Java Home: " + scanner.nextLine());
        System.out.println("Java Vendor: " + scanner.nextLine());
        System.out.println("Java Vendor URL: " + scanner.nextLine());
        System.out.println("Java Class Path: " + scanner.nextLine());
    }
}

