public class AreaPerimeter {
    public static void main(String[] args) {
        int width = 5.5;
        int height = 8.5;
        int area = width * height;
        int perimeter = 2 * (width + height);
        System.out.println("Area is: " + area);
        System.out.println("Perimeter is: " + perimeter);
    }
}

