public class CompareNumbers {
    public static void main(String[] args) {
        int num1 = 25;
        int num2 = 39;

        if (num1!= num2) {
            System.out.println("25!= 39");
        } else if (num1 < num2) {
            System.out.println("25 < 39");
        } else if (num1 <= num2) {
            System.out.println("25 <= 39");
        } else {
            System.out.println("25 == 39");
        }
    }
}

